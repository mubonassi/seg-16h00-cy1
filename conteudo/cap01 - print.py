#Tipos de Informações
#Entrada e Saída
#Saída: É quando a informação sai do computador. Quando o computador envia a informação.
#Entrada: É quando a informação vem para o computador. Quando o computador recebe a informação.

#Comandos/Funções
#Comandos executam instruções para fins de uma tarefa
#função() -> função simples
#função(parametro) -> função com parametros

#Exemplo de função: print() -> ele vai exibir uma informação de SAÍDA
#\n -> quebra linha no texto
print("Hello, World!\nOlá, Mundo!")

#Tipos de Dados

#String -> Texto -> Cadeia de Caracteres
print("Sei lá")
#Int -> Número Inteiro -> 0,1,2,3...9
print(39)
#Float -> Número Real -> Número Flutuante -> 10.8,3.1,87.2,1.0
print(23.87)

#Boolean -> Booleano -> Verdadeiro/Falso -> Binário -> Sim/Não
print(True)
print(False)
#Lógico -> Executar calculos e comandos -> E exibe o resultado
print(10-20)